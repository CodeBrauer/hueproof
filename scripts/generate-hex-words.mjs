// Regenerates src/data/hex-words.ts: the six-digit hex codes that spell an English word in leetspeak.
// Usage: node scripts/generate-hex-words.mjs <path to words.txt from github.com/melted/hexwords>
// The source list and the letter mapping are those of melted/hexwords (ISC); see the header written below.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://github.com/melted/hexwords";
const SOURCE_COMMIT = "15a33fc8480f08cc7d5dad2b66b45a9bdac3c687";
const RETRIEVED_ON = "2026-11-15";
const WORD_LENGTH = 6;
// Letters that are not hex digits but look like one: o -> 0, l -> 1, z -> 2, s -> 5, g -> 9.
const LEET = { o: "0", l: "1", z: "2", s: "5", g: "9" };
// Hand-picked removals: slurs, and words that are offensive in common use.
const EXCLUDED_WORDS = new Set(["dagoes", "fagald", "fagged", "lesbos"]);
// The source capitalizes some common words ("Coffee"), so capitalized entries are dropped as proper nouns except these.
const CAPITALIZED_WORDS_KEPT = new Set([
  "azalea",
  "beagle",
  "bodega",
  "coffee",
  "colada",
  "elodea",
  "fables",
  "fleece",
  "galago",
  "scales",
]);

const hexOf = (word) => [...word].map((letter) => LEET[letter] ?? letter).join("");

const [, , sourcePath] = process.argv;
if (!sourcePath) throw new Error("Pass the path to words.txt as the first argument.");

const words = readFileSync(sourcePath, "utf8").split("\n");
const entries = new Map();
for (const word of words) {
  const lower = word.toLowerCase();
  if (lower.length !== WORD_LENGTH || EXCLUDED_WORDS.has(lower)) continue;
  // Letters only; capitalized entries are mostly names, so they need to be on the keep list.
  const isCommonWord = /^[a-z]+$/.test(word) || CAPITALIZED_WORDS_KEPT.has(lower);
  const hex = hexOf(lower);
  if (isCommonWord && /^[0-9a-f]+$/.test(hex)) entries.set(hex, lower);
}

const body = [...entries].sort(([a], [b]) => a.localeCompare(b)).map(([hex, word]) => `  "${hex}": "${word}",`);
const header = `// Hex codes that spell an English word, for the "hex word" line in the color details.
// Generated by scripts/generate-hex-words.mjs; do not edit by hand.
//
// Source: ${SOURCE_URL} (commit ${SOURCE_COMMIT.slice(0, 7)}), word list words.txt (Webster's Second International)
// License: ISC. Copyright (c) 2024 Niklas Larsson
//   Permission to use, copy, modify, and/or distribute this software for any purpose with or without fee is
//   hereby granted, provided that the above copyright notice and this permission notice appear in all copies.
//   The software is provided "as is" and the author disclaims all warranties.
// Retrieved: ${RETRIEVED_ON}
// Method: every six-letter word made only of a-f and o, l, z, s, g, with o, l, z, s, g read as
//   0, 1, 2, 5, 9 (the mapping of the source project). The keys are the resulting lowercase hex digits without "#".
// Filter: capitalized entries (mostly names) are dropped except ${CAPITALIZED_WORDS_KEPT.size} common words;
//   ${EXCLUDED_WORDS.size} entries were removed by hand because they are slurs or offensive in common use.
`;
const file = `${header}\nexport const HEX_WORDS: Record<string, string> = {\n${body.join("\n")}\n};\n`;
writeFileSync(fileURLToPath(new URL("../src/data/hex-words.ts", import.meta.url)), file);
console.log(`${entries.size} hex words written`);
